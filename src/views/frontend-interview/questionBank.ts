const q = (
  id: string,
  title: string,
  level: QuestionLevel,
  tags: string[],
  answer: string[]
): InterviewQuestion => ({
  id,
  title,
  level,
  tags,
  answer
})

const section = (
  key: string,
  title: string,
  desc: string,
  questions: InterviewQuestion[]
): InterviewSection => ({
  key,
  title,
  desc,
  questions
})

const normalizeKey = (value: string) => value.trim().toLowerCase()

const appendGeneratedSections = (
  target: InterviewSection[],
  incoming: InterviewSection[]
) => {
  const existingQuestionTitles = new Set(
    target.flatMap((item) =>
      item.questions.map((question) => normalizeKey(question.title))
    )
  )
  const existingSectionKeys = new Set(target.map((item) => item.key))

  incoming.forEach((item) => {
    const questions = item.questions.filter((question) => {
      const normalizedTitle = normalizeKey(question.title)
      if (existingQuestionTitles.has(normalizedTitle)) {
        return false
      }

      existingQuestionTitles.add(normalizedTitle)
      return true
    })

    if (!questions.length) {
      return
    }

    let nextKey = item.key
    let suffix = 2
    while (existingSectionKeys.has(nextKey)) {
      nextKey = `${item.key}-${suffix}`
      suffix += 1
    }
    existingSectionKeys.add(nextKey)

    target.push({
      ...item,
      key: nextKey,
      questions
    })
  })
}

